def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--section", type=int, help="run one checkpoint 1..21")
    ap.add_argument("--no-report", action="store_true", help="console only")
    ap.add_argument("--skip-cross-cutting", action="store_true")
    args = ap.parse_args()

    rep = Report()
    print("\n  FinSight — End-to-End Validation\n  " + "=" * 60)
    secs = [_SECTIONS[args.section - 1]] if args.section else _SECTIONS
    for fn in secs:
        print(f"\n  -- {fn.__doc__ or fn.__name__} --" if False else "")
        try:
            fn(rep)
        except Exception as exc:  # noqa: BLE001
            rep.add(fn.__name__, "checkpoint executed", "no exception",
                    f"{type(exc).__name__}: {exc}", "FAIL")
    if not args.section and not args.skip_cross_cutting:
        sec_cross_cutting(rep)

    c = rep.counts()
    print("\n  " + "=" * 60)
    print(f"  TOTAL {len(rep.rows)}  |  PASS {c['PASS']}  FAIL {c['FAIL']}  "
          f"BLOCKED {c['BLOCKED']}  WARN {c['WARN']}  SKIP {c['SKIP']}")
    print("  " + "=" * 60)

    if not args.no_report and not args.section:
        out = REPO / "docs" / "testing" / "E2E_REPORT.md"
        out.parent.mkdir(parents=True, exist_ok=True)
        rep.write_md(out)
        print(f"  report -> {out.relative_to(REPO)}")

    if c["FAIL"]:
        print(f"\n  {c['FAIL']} FAIL(s) - real defects. Review before any change.")
        return 1
    if c["BLOCKED"]:
        print(f"\n  {c['BLOCKED']} BLOCKED - run scripts/run_e2e_pipeline.sh to "
              "populate, then re-validate.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
