    r.add("19 Neo4j", "Transaction nodes", ">= 1", txn, "PASS" if (txn or 0) > 0 else "BLOCKED")
    r.add("19 Neo4j", "SENT relationships", ">= 1", sent, "PASS" if (sent or 0) > 0 else "BLOCKED")
    r.add("19 Neo4j", "RECEIVED_BY relationships", ">= 1", recv,
          "PASS" if (recv or 0) > 0 else "BLOCKED")
    ring = neo4j_scalar(
        "MATCH (s:Account)-[:SENT]->(:Transaction)-[:RECEIVED_BY]->(rx:Account) "
        "WITH rx, count(DISTINCT s) AS n WHERE n > 3 RETURN count(rx)")
    r.add("19 Neo4j", "fraud-ring query (> 3 distinct senders)", ">= 0 accounts",
          ring, "PASS" if ring is not None else "BLOCKED")


