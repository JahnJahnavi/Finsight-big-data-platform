def sh(*cmd, timeout=240, stdin=None):
    return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout,
                          input=stdin, cwd=REPO)


def docker_running(name: str) -> bool:
    r = sh("docker", "inspect", "-f", "{{.State.Running}}", name)
    return r.stdout.strip() == "true"


def http_get(url: str, timeout=8):
    import urllib.request
    try:
        with urllib.request.urlopen(url, timeout=timeout) as resp:
            return resp.status, resp.read().decode("utf-8", "replace")
    except Exception as exc:  # noqa: BLE001
        return None, str(exc)


def hive(sql: str):
    r = sh("docker", "exec", HS2, "beeline", "-u",
           "jdbc:hive2://localhost:10000/finsight", "--silent=true",
           "--showHeader=true", "--outputformat=csv2", "-e", sql)
    lines = [l for l in r.stdout.splitlines()
             if l.strip() and not any(n in l for n in _NOISE)]
    return lines, (r.stdout + r.stderr)


def hive_scalar(sql: str):
    lines, raw = hive(sql)
    if len(lines) >= 2:
        try:
            return float(lines[1].split(",")[0])
        except ValueError:
            return lines[1].split(",")[0]
    return None


def mongo_eval(js: str):
    r = sh("docker", "exec", MONGO, "mongosh", MONGO_URI, "--quiet", "--eval",
           f"print(JSON.stringify(({js})))")
    for ln in reversed([l for l in r.stdout.splitlines() if l.strip()]):
        try:
            return json.loads(ln)
        except json.JSONDecodeError:
            continue
    return None


def neo4j_scalar(cypher: str):
    try:
        from neo4j import GraphDatabase
    except ModuleNotFoundError:
        return None
    try:
        d = GraphDatabase.driver(NEO4J_URI, auth=("neo4j", NEO4J_PW))
        with d.session() as s:
            rec = s.run(cypher).single()
        d.close()
        return rec[0] if rec else None
    except Exception:  # noqa: BLE001
        return None


def hdfs_test(path: str, flag="-e") -> bool:
    return sh("docker", "exec", NN, "hdfs", "dfs", "-test", flag, path).returncode == 0


def hdfs_ls(path: str) -> list[str]:
    r = sh("docker", "exec", NN, "hdfs", "dfs", "-ls", path)
    return [l.split()[-1] for l in r.stdout.splitlines() if l.startswith(("d", "-"))]


def kafka_offsets(topic: str):
    r = sh("docker", "exec", KAFKA, "kafka-run-class",
           "kafka.tools.GetOffsetShell", "--broker-list", "kafka:29092",
           "--topic", topic)
    parts, total = [], 0
    for ln in r.stdout.splitlines():
        m = re.match(rf"{re.escape(topic)}:(\d+):(\d+)", ln.strip())
        if m:
            parts.append(int(m.group(1)))
            total += int(m.group(2))
    return (len(parts), total) if parts else (None, None)


def read_parquet_dir(hdfs_dir: str):
    """-> (pyarrow schema names list, row count) or (None, None)."""
    try:
        import pyarrow.parquet as pq
    except ModuleNotFoundError:
        return None, None
    if not hdfs_test(hdfs_dir):
        return None, None
    entries = hdfs_ls(hdfs_dir)
    files = [f for f in entries if f.endswith(".parquet")]
    # one level of Hive-style partition dirs (e.g. alert_date=2023-01-08/)
    for d in entries:
        if "=" in Path(d).name and "." not in Path(d).name:
            files += [f for f in hdfs_ls(d) if f.endswith(".parquet")]
    if not files:
        return None, None
    tmp = Path(tempfile.mkdtemp())
    try:
        cols, rows = None, 0
        for f in files[:20]:
            local = tmp / Path(f).name
            if sh("docker", "exec", NN, "hdfs", "dfs", "-get", "-f", f,
                  f"/tmp/{local.name}").returncode:
                continue
            sh("docker", "cp", f"{NN}:/tmp/{local.name}", str(local))
            sh("docker", "exec", NN, "rm", "-f", f"/tmp/{local.name}")
            if not local.exists():
                continue
            t = pq.read_table(local)
            cols = list(t.schema.names) if cols is None else cols
            rows += t.num_rows
        return cols, rows
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def csv_header(path: Path) -> list[str]:
    if not path.is_file():
        return []
    with path.open(encoding="utf-8") as fh:
        return fh.readline().strip().split(",")


def csv_rows(path: Path) -> int:
    if not path.is_file():
        return 0
    with path.open(encoding="utf-8") as fh:
        return max(0, sum(1 for _ in fh) - 1)


