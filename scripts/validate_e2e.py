# --------------------------------------------------------------------------- #
class Report:
    def __init__(self) -> None:
        self.rows: list[dict] = []

    def add(self, component: str, test: str, expected: str, actual: str,
            status: str) -> None:
        self.rows.append(dict(component=component, test=test, expected=expected,
                              actual=str(actual)[:220], status=status))
        mark = {"PASS": "PASS", "FAIL": "FAIL", "BLOCKED": "BLKD", "WARN": "WARN",
                "SKIP": "SKIP"}[status]
        print(f"  [{mark}] {component:<22} {test}")
        if status in ("FAIL", "BLOCKED", "WARN"):
            print(f"         expected: {expected}")
            print(f"         actual  : {actual}")

    def counts(self) -> dict:
        c = {k: 0 for k in ("PASS", "FAIL", "BLOCKED", "WARN", "SKIP")}
        for r in self.rows:
            c[r["status"]] += 1
        return c

    def write_md(self, path: Path) -> None:
        c = self.counts()
        lines = [
            "# FinSight — End-to-End Validation Report",
            "",
            f"_Generated by `scripts/validate_e2e.py` — {_now()}_",
            "",
            f"**Total {len(self.rows)} · PASS {c['PASS']} · FAIL {c['FAIL']} · "
            f"BLOCKED {c['BLOCKED']} · WARN {c['WARN']} · SKIP {c['SKIP']}**",
            "",
            "## Pipeline flows",
            "",
            "| Flow | Checkpoints | Worst status |",
            "|---|---|---|",
        ]
        flows = [
            ("Transactions.csv → Producer → txn-raw → Fraud Streaming → txn-flagged",
             ("1 ", "2 ", "6 ", "7 ")),
            ("txn-raw → Kafka Connect → HDFS → Parquet → Hive → Spark SQL",
             ("3 ", "4 ", "5 ", "12 ", "13 ", "14 ", "15 ", "16 ", "17 ")),
            ("HDFS → Risk Scoring → risk_scores", ("10 ",)),
            ("HDFS → CLV Scoring → clv_scores", ("11 ",)),
            ("txn-raw → Churn Streaming → txn-churn / churn_alerts", ("8 ", "9 ")),
            ("MongoDB → Customer Profiles", ("18 ",)),
            ("Neo4j → Fraud Graph → Fraud Ring Detection", ("19 ",)),
            ("Hive + MongoDB + Spark → Alteryx → Power BI", ("20 ", "21 ")),
        ]
        order = {"FAIL": 0, "BLOCKED": 1, "WARN": 2, "SKIP": 3, "PASS": 4}
        for label, prefixes in flows:
            sts = [row["status"] for row in self.rows
                   if any(row["component"].startswith(p) for p in prefixes)]
            worst = min(sts, key=lambda s: order[s]) if sts else "SKIP"
            lines.append(f"| {label} | {', '.join(p.strip() for p in prefixes)} | {worst} |")
        lines += [
            "",
            "## Checkpoint detail",
            "",
            "| Component | Test | Expected | Actual | Status |",
            "|---|---|---|---|---|",
        ]
        for r in self.rows:
            esc = lambda s: str(s).replace("|", "\\|").replace("\n", " ")
            lines.append(f"| {esc(r['component'])} | {esc(r['test'])} | "
                         f"{esc(r['expected'])} | {esc(r['actual'])} | {r['status']} |")
        lines += ["", "## Legend", "",
                  "- **PASS** — checkpoint verified.",
                  "- **FAIL** — a real defect; investigate before any change.",
                  "- **BLOCKED** — upstream output not present; run the named job "
                  "(`scripts/run_e2e_pipeline.sh`) then re-validate.",
                  "- **WARN** — works but degraded (usually a synthetic-data quirk, "
                  "documented in `docs/testing/known-issues.md`).", ""]
        path.write_text("\n".join(lines), encoding="utf-8")


def _now() -> str:
    import datetime as _d
    return _d.datetime.now(_d.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


