def sec_cross_cutting(r: Report):
    # -- no secrets committed --
    tracked = sh("git", "-C", str(REPO), "ls-files").stdout.splitlines()
    env_tracked = [f for f in tracked if f == ".env" or f.endswith("/.env")]
    r.add("X Secrets", ".env not tracked", "0 tracked .env files",
          env_tracked or "none", "PASS" if not env_tracked else "FAIL")
    key_files = [f for f in tracked if f.endswith((".pem", ".key", ".p12", ".pfx"))]
    r.add("X Secrets", "no private-key files tracked", "0", key_files or "none",
          "PASS" if not key_files else "FAIL")
    grep = sh("git", "-C", str(REPO), "grep", "-nI", "-E",
              r"CHANGE_ME_[a-z_]+_pw\s*=\s*\S|BEGIN (RSA|OPENSSH|PRIVATE)",
              "--", ":!*.md", ":!.env.example")
    hits = [l for l in grep.stdout.splitlines() if l.strip()]
    r.add("X Secrets", "no real credentials in tracked source", "0 hits",
          hits[:3] or "none", "PASS" if not hits else "FAIL")

    # -- no large datasets committed --
    big = []
    for f in tracked:
        p = REPO / f
        if p.is_file() and p.stat().st_size > 5_000_000:
            big.append(f"{f} ({p.stat().st_size // 1024}KB)")
    r.add("X Large files", "no tracked file > 5 MB", "0", big or "none",
          "PASS" if not big else "FAIL")
    data_ext = [f for f in tracked
                if f.endswith((".parquet", ".avro"))
                or (f.endswith(".csv") and not f.startswith("tests/"))]
    r.add("X Large files", "no dataset files tracked (.parquet/.csv/.avro)", "0",
          data_ext or "none", "PASS" if not data_ext else "FAIL")

    # -- services reachable --
    for name in ("finsight-kafka", "finsight-kafka-connect", "finsight-namenode",
                 "finsight-datanode", "finsight-spark-master", "finsight-spark-worker",
                 "finsight-hive-metastore", "finsight-hiveserver2", "finsight-mongodb",
                 "finsight-neo4j", "finsight-hive-postgres"):
        up = docker_running(name)
        r.add("X Services", name, "running", up, "PASS" if up else "FAIL")


